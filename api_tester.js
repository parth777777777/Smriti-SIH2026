#!/usr/bin/env node

/**
 * Smriti V1 API Tester
 *
 * Dependency-free integration tester for the current Smriti API surface.
 *
 * Requirements:
 *   - Node.js 18+ (uses built-in fetch)
 *   - Node/Express backend running on port 5000
 *   - FastAPI assessment engine running on port 8000 (optional for internal tests)
 *
 * Run:
 *   node api_tester.js
 *
 * Optional environment variables:
 *   BACKEND_URL=http://127.0.0.1:5000
 *   ASSESSMENT_URL=http://127.0.0.1:8000
 *   TEST_PATIENT_EMAIL=patient@example.com
 *   TEST_CAREGIVER_EMAIL=caregiver@example.com
 *
 * The test data is based on the current verified Smriti V1 API contract.
 */

'use strict';

const BACKEND_URL = process.env.BACKEND_URL || 'http://127.0.0.1:5000';
const ASSESSMENT_URL =
  process.env.ASSESSMENT_URL || 'http://127.0.0.1:8000';

const PATIENT_EMAIL =
  process.env.TEST_PATIENT_EMAIL || 'patient@example.com';
const CAREGIVER_EMAIL =
  process.env.TEST_CAREGIVER_EMAIL || 'caregiver@example.com';

const results = {
  passed: 0,
  failed: 0,
  skipped: 0,
};

// Every HTTP interaction is documented here and written to disk at the end.
// JWTs are redacted so this file is safe to commit as development evidence.
const apiLog = {
  metadata: {
    generated_at: new Date().toISOString(),
    backend_url: BACKEND_URL,
    assessment_url: ASSESSMENT_URL,
    description:
      'Smriti V1 API request/response evidence generated by api_tester.js',
  },
  interactions: [],
};

function redactSecrets(value) {
  if (typeof value === 'string') {
    // Redact JWT-like bearer tokens and common JWT response values.
    if (
      value.length > 40 &&
      value.split('.').length === 3 &&
      /^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(value)
    ) {
      return '[REDACTED_JWT]';
    }
    return value;
  }

  if (Array.isArray(value)) {
    return value.map(redactSecrets);
  }

  if (value && typeof value === 'object') {
    const output = {};
    for (const [key, item] of Object.entries(value)) {
      if (
        ['authorization', 'access_token', 'token', 'password'].includes(
          key.toLowerCase()
        )
      ) {
        output[key] = '[REDACTED]';
      } else {
        output[key] = redactSecrets(item);
      }
    }
    return output;
  }

  return value;
}

function sanitizeHeaders(headers) {
  const output = {};
  if (!headers) return output;

  for (const [key, value] of Object.entries(headers)) {
    output[key] =
      key.toLowerCase() === 'authorization'
        ? 'Bearer [REDACTED_JWT]'
        : value;
  }

  return output;
}

function logInteraction({
  request,
  response,
  name,
  purpose,
  expected,
  observed,
}) {
  apiLog.interactions.push({
    id: apiLog.interactions.length + 1,
    name,
    purpose,
    expected: expected || null,
    request: redactSecrets(request),
    response: {
      status: response.status,
      headers: sanitizeHeaders(response.headers),
      body: redactSecrets(response.body),
    },
    observed: observed || null,
  });
}

async function writeApiLog() {
  const outputPath =
    process.env.API_LOG_FILE ||
    'api_test_requests_responses.json';

  await require('fs').promises.writeFile(
    outputPath,
    JSON.stringify(apiLog, null, 2),
    'utf8'
  );

  console.log(`\nAPI evidence log written to: ${outputPath}`);
  console.log(
    `Documented HTTP interactions: ${apiLog.interactions.length}`
  );
}

function pass(name, details = '') {
  results.passed += 1;
  console.log(`✅ PASS  ${name}${details ? ` — ${details}` : ''}`);
}

function fail(name, details = '') {
  results.failed += 1;
  console.error(`❌ FAIL  ${name}${details ? ` — ${details}` : ''}`);
}

function skip(name, details = '') {
  results.skipped += 1;
  console.log(`⚠️  SKIP  ${name}${details ? ` — ${details}` : ''}`);
}

function assert(condition, name, details = '') {
  if (condition) {
    pass(name, details);
    return true;
  }

  fail(name, details);
  return false;
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

async function request(baseUrl, path, options = {}) {
  const url = `${baseUrl}${path}`;

  let response;
  try {
    response = await fetch(url, options);
  } catch (error) {
    const failedResponse = {
      url,
      status: 0,
      headers: new Headers(),
      body: null,
      raw: '',
    };

    logInteraction({
      name: `${options.method || 'GET'} ${path}`,
      purpose: 'HTTP request',
      request: {
        method: options.method || 'GET',
        url,
        headers: options.headers || {},
        body: options.body ? safeJsonParse(options.body) : null,
      },
      response: failedResponse,
      observed: { network_error: error.message },
    });

    throw new Error(`Request failed for ${url}: ${error.message}`);
  }

  const text = await response.text();

  let body = null;
  if (text.length > 0) {
    try {
      body = JSON.parse(text);
    } catch {
      body = text;
    }
  }

  const result = {
    url,
    status: response.status,
    headers: response.headers,
    body,
    raw: text,
  };

  logInteraction({
    name: `${options.method || 'GET'} ${path}`,
    purpose: 'HTTP request',
    request: {
      method: options.method || 'GET',
      url,
      headers: options.headers || {},
      body: options.body ? safeJsonParse(options.body) : null,
    },
    response: result,
  });

  return result;
}

function safeJsonParse(value) {
  try {
    return JSON.parse(value);
  } catch {
    return value;
  }
}

function bearer(token) {
  return {
    Authorization: `Bearer ${token}`,
  };
}

function assertJson(response, name) {
  return assert(
    isPlainObject(response.body) || Array.isArray(response.body),
    name,
    `HTTP ${response.status}`
  );
}

function logResponse(label, response) {
  console.log(`\n--- ${label} ---`);
  console.log(`HTTP ${response.status}`);
  console.log(
    typeof response.body === 'string'
      ? response.body
      : JSON.stringify(response.body, null, 2)
  );
}

async function login(email) {
  const response = await request(BACKEND_URL, '/auth/login', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ email }),
  });

  assert(response.status === 200, `POST /auth/login (${email})`);

  if (response.status !== 200 || !isPlainObject(response.body)) {
    return null;
  }

  const token = response.body.access_token;
  assert(
    typeof token === 'string' && token.length > 0,
    `Login returns access_token (${email})`
  );

  return {
    token,
    user: response.body.user,
  };
}

