async function testFastApiOptional() {
  console.log('\n==============================');
  console.log('FASTAPI INTERNAL SERVICE TESTS');
  console.log('==============================');

  try {
    const health = await request(ASSESSMENT_URL, '/');
    assert(
      health.status === 200,
      'FastAPI GET / health',
      `expected 200, got ${health.status}`
    );
    assert(
      isPlainObject(health.body) && health.body.status === 'ok',
      'FastAPI health response shape'
    );

    const payload = {
      profile: {
        patient_id: 'P_API_TEST',
        current_difficulty: 1,
      },
      raw_session: buildMemoryMatchTelemetry(
        'sess_api_test',
        'P_API_TEST'
      ),
    };

    const processed = await request(
      ASSESSMENT_URL,
      '/v1/process-session',
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(payload),
      }
    );

    assert(
      processed.status === 200,
      'FastAPI POST /v1/process-session',
      `expected 200, got ${processed.status}`
    );

    if (processed.status === 200 && isPlainObject(processed.body)) {
      const body = processed.body;

      assert(body.session_id === 'sess_api_test', 'Assessment session_id');
      assert(body.domain === 'MEMORY', 'Assessment domain');
      assert(isPlainObject(body.features), 'Assessment features object');
      assert(
        body.features.pairs_presented === 4,
        'Assessment pairs_presented',
        'expected authoritative num_pairs=4'
      );
      assert(
        body.features.pairs_recalled === 1,
        'Assessment pairs_recalled'
      );
      assert(
        body.features.repeated_selections === 1,
        'Assessment repeated_selections'
      );
      assert(
        isPlainObject(body.normalized_features),
        'Assessment normalized_features object'
      );
      assert(
        isPlainObject(body.domain_score),
        'Assessment domain_score object'
      );
      assert(
        typeof body.domain_score.score === 'number' &&
          body.domain_score.score >= 0 &&
          body.domain_score.score <= 1,
        'Assessment domain score is within [0,1]'
      );
      assert(
        body.baseline === null,
        'First HTTP session baseline is null'
      );
      assert(
        body.deviation === null,
        'First HTTP session deviation is null'
      );
      assert(
        isPlainObject(body.longitudinal) &&
          body.longitudinal.trend === 'INSUFFICIENT_DATA',
        'First HTTP session longitudinal state'
      );
    }

    return true;
  } catch (error) {
    skip(
      'FastAPI internal service tests',
      error.message
    );
    return false;
  }
}

/**
 * Output file format:
 *
 * {
 *   metadata: {
 *     generated_at,
 *     backend_url,
 *     assessment_url,
 *     description,
 *     results
 *   },
 *   interactions: [
 *     {
 *       id,
 *       name,
 *       purpose,
 *       expected,
 *       request: { method, url, headers, body },
 *       response: { status, headers, body },
 *       observed
 *     }
 *   ]
 * }
 *
 * This deliberately captures request/response JSON rather than only PASS/FAIL,
 * making the file useful as API evidence and frontend integration reference.
 */
async function testBackend() {
  console.log('\n==============================');
  console.log('NODE / EXPRESS API TESTS');
  console.log('==============================');

  // Health/root route
  try {
    const root = await request(BACKEND_URL, '/');

    // The public backend may or may not expose GET /.
    if (root.status === 200) {
      pass('Backend GET /', 'HTTP 200');
    } else if (root.status === 404) {
      skip('Backend GET /', 'route not implemented');
    } else {
      fail('Backend GET /', `HTTP ${root.status}`);
    }
  } catch (error) {
    fail('Backend connectivity', error.message);
    return;
  }

  const patient = await login(PATIENT_EMAIL);
  const caregiver = await login(CAREGIVER_EMAIL);

  if (!patient || !caregiver) {
    fail('Authentication setup', 'could not obtain both test tokens');
    return;
  }

  const patientToken = patient.token;
  const caregiverToken = caregiver.token;
  const patientId = patient.user?.id || 'P001';

  // Patient profile
  let response = await request(BACKEND_URL, '/patients/me', {
    headers: bearer(patientToken),
  });
  assert(response.status === 200, 'GET /patients/me');
  if (response.status === 200) {
    assertJson(response, 'GET /patients/me returns JSON');
    assert(
      isPlainObject(response.body) &&
        response.body.id === patientId,
      'Patient profile has expected patient id'
    );
  }

  // Progress
  response = await request(BACKEND_URL, '/patients/me/progress', {
    headers: bearer(patientToken),
  });
  assert(response.status === 200, 'GET /patients/me/progress');
  if (response.status === 200) {
    assertJson(response, 'GET /patients/me/progress returns JSON');
  }

  // Reminders
  response = await request(BACKEND_URL, '/patients/me/reminders', {
    headers: bearer(patientToken),
  });
  assert(response.status === 200, 'GET /patients/me/reminders');
  if (response.status === 200) {
    assert(
      Array.isArray(response.body),
      'GET /patients/me/reminders returns array'
    );
  }

  // Medications
  response = await request(BACKEND_URL, '/patients/me/medications', {
    headers: bearer(patientToken),
  });
  assert(response.status === 200, 'GET /patients/me/medications');
  if (response.status === 200) {
    assert(
      Array.isArray(response.body),
      'GET /patients/me/medications returns array'
    );
  }

  // Activities
  response = await request(BACKEND_URL, '/activities', {
    headers: bearer(patientToken),
  });
  assert(response.status === 200, 'GET /activities');
  if (response.status === 200) {
    assert(
      Array.isArray(response.body) && response.body.length > 0,
      'GET /activities returns non-empty array'
    );
  }

  // Activity detail
  response = await request(BACKEND_URL, '/activities/A101', {
    headers: bearer(patientToken),
  });
  assert(response.status === 200, 'GET /activities/A101');
  if (response.status === 200) {
    assert(
      isPlainObject(response.body) &&
        typeof response.body.title === 'string',
      'GET /activities/A101 response shape'
    );
  }

  // Existing session history before test completion
  response = await request(
    BACKEND_URL,
    '/patients/me/session-history',
    {
      headers: bearer(patientToken),
    }
  );
  assert(
    response.status === 200,
    'GET /patients/me/session-history (before)'
  );
  const historyBefore =
    response.status === 200 && Array.isArray(response.body)
      ? response.body
      : [];

  // Start session
  response = await request(
    BACKEND_URL,
    '/activities/memory_match_v1/sessions',
    {
      method: 'POST',
      headers: bearer(patientToken),
    }
  );
  assert(
    response.status === 201,
    'POST /activities/memory_match_v1/sessions'
  );

  if (
    response.status !== 201 ||
    !isPlainObject(response.body) ||
    typeof response.body.session_id !== 'string'
  ) {
    fail(
      'Session start response contains session_id',
      'cannot continue session completion test'
    );
  } else {
    const sessionId = response.body.session_id;

    assert(
      response.body.status === 'STARTED',
      'Session start status is STARTED'
    );

    // Complete session
    const telemetry = buildMemoryMatchTelemetry(
      sessionId,
      patientId
    );

    response = await request(
      BACKEND_URL,
      `/activities/memory_match_v1/sessions/${encodeURIComponent(
        sessionId
      )}/complete`,
      {
        method: 'POST',
        headers: {
          ...bearer(patientToken),
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({ telemetry }),
      }
    );

    assert(
      response.status === 200,
      'POST /activities/:id/sessions/:session_id/complete'
    );

    if (response.status === 200 && isPlainObject(response.body)) {
      const body = response.body;

      assert(
        body.session_id === sessionId,
        'Completed assessment session_id matches started session'
      );
      assert(
        body.status === 'COMPLETED',
        'Completed session status is COMPLETED'
      );
      assert(
        body.domain === 'MEMORY',
        'Completed session domain is MEMORY'
      );
      assert(
        isPlainObject(body.features),
        'Completed session contains features'
      );
      assert(
        body.features.pairs_presented === 4,
        'Completed session pairs_presented === 4'
      );
      assert(
        isPlainObject(body.normalized_features),
        'Completed session contains normalized_features'
      );
      assert(
        isPlainObject(body.domain_score),
        'Completed session contains domain_score'
      );
      assert(
        typeof body.domain_score.score === 'number' &&
          body.domain_score.score >= 0 &&
          body.domain_score.score <= 1,
        'Completed domain score is within [0,1]'
      );
      assert(
        Object.prototype.hasOwnProperty.call(body, 'baseline'),
        'Completed result includes baseline field'
      );
      assert(
        Object.prototype.hasOwnProperty.call(body, 'deviation'),
        'Completed result includes deviation field'
      );
      assert(
        isPlainObject(body.longitudinal),
        'Completed result includes longitudinal field'
      );

      // Fetch history again and verify the new result was persisted.
      response = await request(
        BACKEND_URL,
        '/patients/me/session-history',
        {
          headers: bearer(patientToken),
        }
      );

      assert(
        response.status === 200,
        'GET /patients/me/session-history (after)'
      );

      if (response.status === 200 && Array.isArray(response.body)) {
        assert(
          response.body.length >= historyBefore.length,
          'Session history does not shrink after completion'
        );

        const found = response.body.some(
          (item) => item?.session_id === sessionId
        );

        assert(
          found,
          'Completed session appears in patient session history'
        );
      }
    }
  }

  // Caregiver list
  response = await request(
    BACKEND_URL,
    '/caregiver/patients',
    {
      headers: bearer(caregiverToken),
    }
  );
  assert(response.status === 200, 'GET /caregiver/patients');
  if (response.status === 200) {
    assert(
      Array.isArray(response.body),
      'GET /caregiver/patients returns array'
    );
  }

  // Caregiver alerts
  response = await request(
    BACKEND_URL,
    '/caregiver/alerts',
    {
      headers: bearer(caregiverToken),
    }
  );
  assert(response.status === 200, 'GET /caregiver/alerts');
  if (response.status === 200) {
    assert(
      Array.isArray(response.body),
      'GET /caregiver/alerts returns array'
    );
  }

  // Caregiver patient history
  response = await request(
    BACKEND_URL,
    `/caregiver/patients/${encodeURIComponent(
      patientId
    )}/session-history`,
    {
      headers: bearer(caregiverToken),
    }
  );
  assert(
    response.status === 200,
    'GET /caregiver/patients/:id/session-history'
  );
  if (response.status === 200) {
    assert(
      Array.isArray(response.body),
      'Caregiver session history returns array'
    );
  }

  // Auth failure
  response = await request(BACKEND_URL, '/patients/me');
  assert(
    response.status === 401,
    'GET /patients/me without token returns 401'
  );

  // Role failure
  response = await request(
    BACKEND_URL,
    '/caregiver/alerts',
    {
      headers: bearer(patientToken),
    }
  );
  assert(
    response.status === 403,
    'Patient accessing caregiver route returns 403'
  );
}

async function main() {
  console.log('==============================================');
  console.log('       SMRITI V1 API INTEGRATION TESTER       ');
  console.log('==============================================');
  console.log(`Backend URL:    ${BACKEND_URL}`);
  console.log(`Assessment URL: ${ASSESSMENT_URL}`);
  console.log(`API log file:   ${process.env.API_LOG_FILE || 'api_test_requests_responses.json'}`);
  console.log('');

  try {
    await testBackend();
    await testFastApiOptional();
  } catch (error) {
    console.error('\nFATAL TEST ERROR');
    console.error(error);
    results.failed += 1;
  } finally {
    apiLog.metadata.results = {
      passed: results.passed,
      failed: results.failed,
      skipped: results.skipped,
      result: results.failed > 0 ? 'FAIL' : 'PASS',
    };

    try {
      await writeApiLog();
    } catch (logError) {
      console.error(
        `\nWARNING: could not write API evidence log: ${logError.message}`
      );
      results.failed += 1;
    }
  }

  console.log('\n==============================');
  console.log('FINAL RESULTS');
  console.log('==============================');
  console.log(`Passed:  ${results.passed}`);
  console.log(`Failed:  ${results.failed}`);
  console.log(`Skipped: ${results.skipped}`);

  if (results.failed > 0) {
    console.error('\nAPI TEST RESULT: FAIL');
    process.exitCode = 1;
  } else {
    console.log('\nAPI TEST RESULT: PASS');
  }
}

main();
